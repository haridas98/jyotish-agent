let registered = false;

export function registerCoreEntities() {
  if (registered) return;
  registered = true;

  grahas.forEach(([id, short, ru, en, sa, meaning]) => {
    registerEntity(
      baseEntity(
        id,
        "graha",
        short,
        ru,
        en,
        sa,
        `${ru} показывает ${meaning}. Положение грахи читается через дом, знак, управителя, аспекты, силу, достоинство, накшатру и текущие периоды.`,
      ),
    );
  });

  houseSummaries.forEach((summary, index) => {
    const house = index + 1;
    registerEntity(baseEntity(`house.${house}` as EntityId, "house", String(house), `${house} дом`, `${house}th house`, `Bhava ${house}`, summary));
  });

  rashis.forEach(([en, ru, sa, meaning], index) => {
    registerEntity(baseEntity(`rashi.${en}` as EntityId, "rashi", String(index + 1), ru, en, sa, `${ru}: ${meaning}. Значение знака уточняется через стихию, качество, управителя и занятый дом.`));
  });

  vargas.forEach(([id, short, ru, summary]) => {
    registerEntity({
      id,
      kind: "varga",
      terms: { short, ru, en: short },
      summary,
      warning: id === "varga.D60" ? "При неточном времени рождения D60 может быть ненадежной." : undefined,
      sourceIds: [`jyotish.classical.${id}`],
    });
  });
}

function baseEntity(id: EntityId, kind: EntityKind, short: string, ru: string, en: string, sa: string, summary: string): EntityDefinition {
  return {
    id,
    kind,
    terms: { short, ru, en, sa },
    summary,
    sourceIds: [`jyotish.classical.${kind}`],
  };
}
